import { describe, expect, it } from 'vitest';
import { formatPhone, normalizePhone } from './phone';

describe('normalizePhone', () => {
  it.each([
    ['+7 (999) 123-45-67', '79991234567'],
    ['8 999 123 45 67', '79991234567'],
    ['89991234567', '79991234567'],
    ['9991234567', '79991234567'],
    ['  7-999-123-45-67 ', '79991234567'],
    ['+375 (29) 123-45-67', '375291234567'],
    ['80 29 123-45-67', '375291234567'],
  ])('«%s» → %s', (input, digits) => {
    expect(normalizePhone(input)).toEqual({ ok: true, digits });
  });

  it.each([
    ['', 'Введите номер телефона'],
    ['abc', 'Введите номер телефона'],
    ['+7 999 123', 'Поддерживаются номера России (+7) и Беларуси (+375)'],
    ['+1 202 555 0123', 'Поддерживаются номера России (+7) и Беларуси (+375)'],
    ['+49 151 23456789', 'Поддерживаются номера России (+7) и Беларуси (+375)'],
    ['+7 999 123 45 678', 'Поддерживаются номера России (+7) и Беларуси (+375)'],
  ])('«%s» отклоняется', (input, error) => {
    expect(normalizePhone(input)).toEqual({ ok: false, error });
  });
});

describe('formatPhone', () => {
  it('форматирует номера РФ и РБ', () => {
    expect(formatPhone('79991234567')).toBe('+7 999 123-45-67');
    expect(formatPhone('375291234567')).toBe('+375 29 123-45-67');
    expect(formatPhone('12345')).toBe('+12345');
  });
});
